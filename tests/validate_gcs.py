# r17: the file prolog


def check_prolog(lines, filename):
    """Returns (problems, closing line index or -1). The regexes are the standard's; the field walk is
    the rest of r17's text made mechanical: twelve fields, once each, A to L, To Do numbered 1), 2) ...
    and every continuation aligned under the value it continues."""
    problems = []
    if not lines or not PROLOG_OPEN.match(lines[0]):
        return [(1, "r17", "the file must open with the prolog's '/*' line")], -1
    close = -1
    for index in range(1, min(len(lines), PROLOG_SEARCH)):
        if PROLOG_CLOSE.match(lines[index]):
            close = index
            break
    if close < 0:
        return [(1, "r17", "the prolog's closing ' */' line was not found")], -1

    fields = []
    current = None
    for index in range(1, close):
        line = lines[index]
        number = index + 1
        if line == " *":
            current = None
            continue
        if line.rstrip(" ") == " *":
            # The regex lets ' * ' through as a content line of nothing; r17's prose does not.
            problems.append((number, "r17", "a blank prolog line is exactly ' *', with nothing after it"))
            current = None
            continue
        if not PROLOG_INNER.match(line):
            if line.startswith(" * "):
                problems.append((number, "r17", "a prolog line is %d columns; wrap at 150, or end it with "
                                 "'%s' within 180" % (len(line), WIDTH_MARK[CPP].strip())))
            else:
                problems.append((number, "r17", "a prolog line starts with exactly ' * ', or is exactly ' *'"))
            current = None
            continue
        if line.endswith(WIDTH_MARK[CPP]):
            line = line[:-len(WIDTH_MARK[CPP])]
        text = line[3:]
        if re.match(r"\s*History\s*:", text):
            problems.append((number, "r17", "no 'History:' in a prolog; history belongs in CHANGELOG.md (c1)"))
            current = None
            continue
        label = next((f for f in FIELDS if text.startswith(f + ":")), None)
        if label is not None:
            value = text[len(label) + 1:]
            if not value.startswith(" ") or value.startswith("  ") or not value.strip():
                problems.append((number, "r17", "'%s:' takes one space and then its value" % label))
            current = {"label": label, "line": number, "column": 3 + len(label) + 2,
                       "value": value[1:].rstrip(), "more": []}
            fields.append(current)
        elif text.startswith(" "):
            if current is None or current["label"] not in MULTILINE:
                what = "a field" if current is None else "'%s:'" % current["label"]
                problems.append((number, "r17", "a continuation line, but %s takes one line" % what))
                current = None
            else:
                body = line[2:]
                current["more"].append((number, 2 + len(body) - len(body.lstrip(" ")), body.strip()))
        else:
            problems.append((number, "r17", "not one of r17's twelve fields: %s" % text.split(":")[0][:40]))
            current = None

    seen = [f["label"] for f in fields]
    for label in FIELDS:
        if seen.count(label) == 0:
            problems.append((close + 1, "r17", "the '%s:' field is missing" % label))
        elif seen.count(label) > 1:
            later = [f["line"] for f in fields if f["label"] == label][1]
            problems.append((later, "r17", "'%s:' appears %d times" % (label, seen.count(label))))
    order = [FIELDS.index(label) for label in seen]
    for position in range(1, len(order)):
        if order[position] < order[position - 1]:
            problems.append((fields[position]["line"], "r17", "'%s:' comes after '%s:'; r17 orders the fields A to L"
                             % (fields[position]["label"], fields[position - 1]["label"])))
            break

    first = {}
    for field in fields:
        first.setdefault(field["label"], field)
    for field in first.values():
        problems.extend(check_field(field, lines, filename))

    created = first.get("Created")
    modified = first.get("Last Modified")
    if created and modified:
        try:
            if datetime.date.fromisoformat(created["value"]) > datetime.date.fromisoformat(modified["value"]):
                problems.append((modified["line"], "r17", "'Last Modified:' is earlier than 'Created:'"))
        except ValueError:
            pass
    return problems, close


def check_field(field, lines, filename):
    """One field's own rule. The full-line regexes are r17's; the rest is the field's text."""
    label = field["label"]
    value = field["value"]
    number = field["line"]
    line = lines[number - 1]
    problems = []

    def fail(message, at=number):
        problems.append((at, "r17", message))

    if label == "File" and value != filename:
        fail("'File:' says %s, but the file is %s" % (value, filename))
    elif label == "Version" and not PROLOG_VERSION.match(line):
        fail("'Version:' is vMAJOR.MINOR or vMAJOR.MINOR.PATCH")
    elif label in ("Created", "Last Modified"):
        if not PROLOG_DATE.match(line):
            fail("'%s:' is a YYYY-MM-DD date and nothing else" % label)
        else:
            try:
                datetime.date.fromisoformat(value)
            except ValueError:
                fail("'%s:' is not a calendar date: %s" % (label, value))
    elif label == "To Do":
        item = re.match(r"(\d+)\) \S", value)
        if not item or item.group(1) != "1":
            fail("'To Do:' opens with item 1), on the label's own line")
        expected = 2
        text_column = field["column"] + len("1) ")
        for at, column, content in field["more"]:
            numbered = re.match(r"(\d+)\) \S", content)
            if column == field["column"] and numbered:
                if int(numbered.group(1)) != expected:
                    fail("To Do item %s) should be %d)" % (numbered.group(1), expected), at)
                expected = int(numbered.group(1)) + 1
                text_column = column + len(numbered.group(1)) + 2
            elif column == field["column"]:
                fail("a To Do line at the value column starts a numbered item, %d)" % expected, at)
            elif column != text_column:
                fail("a To Do continuation aligns under its item's text, at column %d, not %d" % (text_column + 1, column + 1),
                     at)
    elif label in ("Dependencies", "Reviewers"):
        for at, column, content in field["more"]:
            if column != field["column"]:
                fail("a '%s:' continuation aligns under the value, at column %d, not %d" % (label, field["column"] + 1, column + 1),
                     at)
        if label == "Dependencies":
            joined = " ".join([value] + [content for _, _, content in field["more"]])
            if joined != "None" and not re.fullmatch(r"[^,\s]([^,]*[^,\s])?(, [^,\s]([^,]*[^,\s])?)*", joined):
                fail("'Dependencies:' is None or a comma-separated list")
    elif label == "ISA":
        tokens = value.split(" | ")
        if any(token not in ISA_TOKENS for token in tokens):
            fail("'ISA:' tokens come from {%s}, separated by ' | '" % ", ".join(ISA_TOKENS))
        elif len(set(tokens)) != len(tokens):
            fail("'ISA:' names a token twice")
    elif label == "Thread-safety" and value not in THREAD_SAFETY:
        fail("'Thread-safety:' is one of %s" % ", ".join(THREAD_SAFETY))
    elif label == "License" and not PROLOG_LICENSE.match(line):
        fail("'License:' is an SPDX id, exactly two spaces, then 'Copyright: <holder>'")
    return problems


