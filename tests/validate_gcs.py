# RULE-DEV:r17 GCS r17's file prolog is a C block comment, which Python cannot carry. The module
# docstring below holds the same information in the form the language allows.
"""The mechanical half of GCS v1.1.4, run over src/ and tests/ -- decision D11's validator.

    python tests/validate_gcs.py                       src/ and tests/, which is what CI runs
    python tests/validate_gcs.py src/Ir.h tests/unit   only what is named, inside the same scope
    python tests/validate_gcs.py --format              and clang-format 18.1.3 must be a no-op
    python tests/validate_gcs.py --format --clang-format <path>   that clang-format, not the one on PATH
    python tests/validate_gcs.py --self-test           every rule but tc1 shown firing on a known-bad input

What a machine can check without a compiler, it checks: the r17 prolog (the standard's own regexes and
its twelve fields in order), r8's three-space indent and its ban on tabs, e2's 150 and 180 columns,
tc2's CRLF, and ASCII -- the sources carry no BOM and the project does not pass /utf-8, so a non-ASCII
byte would be read in whatever code page the compiler runs under. With --format it also holds the tree
to clang-format 18.1.3, reported under tc1. Everything else stays with review: naming, the typedef
lattice, whether a comment is true.

include/ is exempt, and the exemption lives here rather than in the CI invocation so that a hand run
cannot reach a different verdict (D11). The six owner-authored headers carry a nonconforming ISA token
and two pre-r17 banners that CLAUDE.md says to report, not fix, so a path that resolves into include/ is
never judged however it is named. tests/fixtures/ is input data (.editorconfig's RULE-DEV:tc2), and
tests/build/, tests/x64/ and __pycache__/ are generated, so none of those is judged either. Any other
file under src/ or tests/ whose type this script has no rules for is a problem rather than a silent
pass, and so is a symbolic link, which Git checks out as a link on Linux and as a text file on Windows.
Paths compare in exact letter case on every host, as Git's do, so a verdict never depends on whether the
file system folds case. The Python checks use the running interpreter's grammar; CI's is 3.12.

Exit status: 0 clean; 1 at least one problem, including a default run that finds nothing to judge; 2 a
usage error, or named paths that leave nothing to judge.
"""

