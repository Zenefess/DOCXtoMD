# Choosing what to judge


def relative(path):
    """Returns the path relative to the repository with forward slashes, or None when it is outside it."""
    try:
        rel = os.path.relpath(os.path.abspath(path), REPO)
    except ValueError:
        return None
    rel = rel.replace(os.sep, "/")
    if rel == ".." or rel.startswith("../"):
        return None
    return rel


def same(a, b):
    return os.path.normcase(a) == os.path.normcase(b)


def verdict_for(rel):
    """Says what happens to one repository-relative path: (kind, reason). kind is 'judge', 'skip',
    'exempt', 'outside' or 'unknown', and reason is the file class for 'judge'."""
    parts = rel.split("/")
    if same(parts[0], EXEMPT):
        return "exempt", EXEMPT_REASON
    if not any(same(parts[0], top) for top in SCOPE):
        return "outside", "outside D11's scope, which is %s" % " and ".join(s + "/" for s in SCOPE)
    for prefix, reason in SKIPPED_DIRS.items():
        size = len(prefix.split("/"))
        if len(parts) >= size and same("/".join(parts[:size]), prefix):
            return "skip", reason
    for part in parts:
        if part in SKIPPED_NAMES:
            return "skip", SKIPPED_NAMES[part]
    for suffix, reason in SKIPPED_SUFFIXES.items():
        if rel.lower().endswith(suffix):
            return "skip", reason
    kind = CLASSES.get(os.path.splitext(rel)[1].lower())
    if kind is None:
        return "unknown", "no rules are defined for this type of file"
    return "judge", kind


def walk(rel_dir):
    """Every file under one repository-relative directory, sorted, pruning what is never judged."""
    found = []
    for here, dirs, files in os.walk(os.path.join(REPO, rel_dir)):
        base = relative(here)
        dirs[:] = sorted(d for d in dirs if verdict_for(base + "/" + d + "/x")[0] not in ("skip", "exempt"))
        found.extend(base + "/" + name for name in sorted(files))
    return found


def judge(candidates, files, problems):
    """Adds each candidate the rules reach to files, and each one no class covers to problems. Returns
    how many were judged, which a default run uses to refuse a vacuous pass."""
    count = 0
    for rel in candidates:
        kind, reason = verdict_for(rel)
        if kind == "judge":
            count += 1
            if rel not in [f for f, _ in files]:
                files.append((rel, reason))
        elif kind == "unknown":
            problems.append((rel, 0, "scope", reason + "; give it a class in validate_gcs.py, or move it"))
    return count


def select(args, notes):
    """Turns the command line into (files, problems): the files to judge, in order, and any path that
    is a problem in itself. A named path that is never judged is explained in notes instead."""
    files = []
    problems = []
    if not args:
        for top in SCOPE:
            if judge(walk(top), files, problems) == 0:
                problems.append((top + "/", 0, "scope", "nothing here to judge, and D11 names this directory"))
        return files, problems
    for name in args:
        full = os.path.abspath(name)
        if not os.path.exists(full):
            raise UsageError("no such file or directory: %s" % name)
        rel = relative(full)
        if rel is None:
            notes.append("%s: not judged -- outside the repository" % name)
            continue
        if rel == ".":
            notes.append("%s: narrowed to %s" % (name, " and ".join(top + "/" for top in SCOPE)))
            notes.append("%s/: not judged -- %s" % (EXEMPT, EXEMPT_REASON))
            for top in SCOPE:
                judge(walk(top), files, problems)
            continue
        directory = os.path.isdir(full)
        kind, reason = verdict_for(rel + "/x" if directory else rel)
        if kind in ("exempt", "outside", "skip"):
            notes.append("%s: not judged -- %s" % (rel, reason))
            continue
        judge(walk(rel) if directory else [rel], files, problems)
    return files, problems


class UsageError(Exception):
    pass


