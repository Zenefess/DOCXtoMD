# Reporting and the command line


def ascii_only(text):
    """Every message is ASCII, so a report reaches any console whole: a file's own bytes quoted in a
    message come out as escapes, whatever the output's encoding."""
    return text.encode("ascii", "backslashreplace").decode("ascii")


def annotate(rel, line, rule, message):
    """A GitHub Actions error annotation, so a failure lands on the line in the pull request's diff."""
    def escape(text, extra=""):
        text = text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
        for c in extra:
            text = text.replace(c, "%%%02X" % ord(c))
        return text
    where = "file=%s" % escape(rel, ":,")
    if line:
        where += ",line=%d" % line
    return "::error %s,title=%s::%s" % (where, escape("GCS " + rule, ":,"), escape(message))


def show(problems):
    on_github = os.environ.get("GITHUB_ACTIONS") == "true"
    for rel, line, rule, message in problems:
        rel = ascii_only(rel)
        message = ascii_only(message)
        print("%s:%s %s: %s" % (rel, "%d:" % line if line else "", rule, message))
        if on_github:
            print(annotate(rel, line, rule, message))


def parse(argv):
    """The command line as a dict, or UsageError."""
    options = {"self_test": False, "format": False, "exe": None, "paths": []}
    index = 0
    while index < len(argv):
        arg = argv[index]
        if arg == "--self-test":
            options["self_test"] = True
        elif arg == "--format":
            options["format"] = True
        elif arg == "--clang-format" or arg.startswith("--clang-format="):
            if "=" in arg:
                value = arg.split("=", 1)[1]
            elif index + 1 < len(argv) and not argv[index + 1].startswith("-"):
                index += 1
                value = argv[index]
            else:
                value = ""
            if not value:
                raise UsageError("--clang-format needs a path")
            options["exe"] = value
        elif arg.startswith("-"):
            raise UsageError("unknown option %s" % arg)
        else:
            options["paths"].append(arg)
        index += 1
    if options["self_test"] and (options["format"] or options["exe"] or options["paths"]):
        raise UsageError("--self-test takes no other argument")
    if options["exe"] and not options["format"]:
        raise UsageError("--clang-format names the formatter --format runs, so it needs --format")
    return options


def main(argv):
    try:
        options = parse(argv)
        if options["self_test"]:
            return self_test()
        chosen = select(options["paths"])
    except UsageError as error:
        print("validate_gcs: %s" % ascii_only(str(error)))
        print(USAGE)
        return 2
    for note in chosen.notes:
        print(ascii_only(note))
    if options["paths"] and not chosen.files and not chosen.problems:
        print("validate_gcs: nothing to check")
        return 2
    problems = chosen.problems + check_files(chosen.files)
    if options["format"]:
        problems.extend(format_check(chosen.files, options["exe"] or "clang-format"))
    show(problems)
    touched = len({p[0] for p in problems})
    print("validate_gcs: %d file%s judged, %d problem%s in %d place%s" % (
        len(chosen.files), "" if len(chosen.files) == 1 else "s", len(problems), "" if len(problems) == 1 else "s",
        touched, "" if touched == 1 else "s"))
    return 1 if problems else 0


