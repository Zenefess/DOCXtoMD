def check_file(rel, kind, data):
    """Every rule the file's class carries, as (line, rule, message) tuples sorted by line."""
    problems = check_bytes(data, kind)
    lines = split_lines(data)
    if kind == CPP:
        prolog, inner = check_prolog(lines, rel.split("/")[-1])
        problems.extend(prolog)
        problems.extend(check_width(lines, kind, inner))
        problems.extend(check_indent(lines))
    elif kind == PYTHON:
        problems.extend(check_width(lines, kind))
        problems.extend(check_python(data))
    else:
        problems.extend(check_width(lines, kind))
    return sorted(problems, key=lambda p: (p[0], p[1]))


def check_files(files, root=REPO):
    """Reads and judges each (rel, kind) pair; a file that cannot be read is a problem, not a crash."""
    problems = []
    for rel, kind in files:
        try:
            with open(os.path.join(root, *rel.split("/")), "rb") as handle:
                data = handle.read()
        except OSError as error:
            problems.append((rel, 0, "scope", "cannot be read: %s" % error.strerror))
            continue
        problems.extend((rel, line, rule, message) for line, rule, message in check_file(rel, kind, data))
    return problems


