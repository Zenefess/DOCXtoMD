def tree_cases(root):
    """Builds small repositories under root and returns (name, ok, got) for select() and check_files()."""
    def make(base, files):
        for rel, data in files.items():
            path = os.path.join(base, *rel.split("/"))
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "wb") as handle:
                handle.write(data)
        return base

    good = cpp(GOOD_PROLOG + GOOD_BODY)
    py = cpp(["# RULE-DEV:r17 the reason", "x = 1"])
    full = make(os.path.join(root, "full"), {"src/Good.cpp": good, "tests/ok.py": py, "tests/notes.txt": b"",
                                             "include/typedefs.h": b"junk", "docs/x.md": b""})
    empty = make(os.path.join(root, "empty"), {"tests/ok.py": py})
    os.makedirs(os.path.join(empty, "src"))
    variant = make(os.path.join(root, "variant"), {"src/Good.cpp": good, "tests/ok.py": py, "Include/typedefs.h": b"junk",
                                                   "tests/Build/probe.cpp": good})
    missing = make(os.path.join(root, "missing"), {"tests/ok.py": py})
    results = []

    def run(name, args, base, wanted_files, wanted_problems, wanted_notes=0):
        try:
            chosen = select(args, base)
            got = ([rel for rel, _ in chosen.files], [(p[0], p[3]) for p in chosen.problems], len(chosen.notes))
            ok = (got[0] == wanted_files and len(got[1]) == len(wanted_problems)
                  and all(any(rel == w[0] and w[1] in text for rel, text in got[1]) for w in wanted_problems) and got[2] == wanted_notes)
        except UsageError as error:
            got, ok = "usage error: %s" % error, wanted_files is None
        results.append((name, ok, got))

    run("a default run judges src/ and tests/, and fails what has no class", [], full,
        ["src/Good.cpp", "tests/ok.py"], [("tests/notes.txt", "no rules")])
    run("a default run over an empty src/ is a problem", [], empty, ["tests/ok.py"], [("src", "nothing here")])
    run("naming the root is the default run", [full], full, ["src/Good.cpp", "tests/ok.py"], [("tests/notes.txt", "no rules")], 2)
    run("naming the root keeps the empty-scope problem", [empty], empty, ["tests/ok.py"], [("src", "nothing here")], 2)
