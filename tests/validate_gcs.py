def matches(got, wanted):
    """True when every wanted (rule, fragment) pair names a distinct problem and nothing else was found."""
    left = list(got)
    for rule, fragment in wanted:
        hit = next((p for p in left if p[1] == rule and fragment in p[2]), None)
        if hit is None:
            return False
        left.remove(hit)
    return not left


