def split_lines(data):
    """Splits the bytes into lines without their terminators. Latin-1 maps each byte to one character,
    so a column is a byte; a byte that is not ASCII is the ASCII rule's to report."""
    text = data.decode("latin-1")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return [line[:-1] if line.endswith("\r") else line for line in lines]


def line_of(data, offset):
    return data.count(b"\n", 0, offset) + 1


def check_bytes(data, kind):
    """tc2's CRLF, r8's no tabs, and ASCII. Each reports its first offence and how many there are,
    because a file saved with the wrong settings breaks one of them on every line."""
    problems = []
    start = len(UTF8_BOM) if kind == MSBUILD and data.startswith(UTF8_BOM) else 0

    def report(rule, offsets, what):
        if offsets:
            more = "" if len(offsets) == 1 else " (%d in all)" % len(offsets)
            problems.append((line_of(data, offsets[0]), rule, what + more))

    report("tc2", [m.start() for m in re.finditer(rb"(?<!\r)\n", data)], "a line ends LF rather than CRLF")
    report("tc2", [m.start() for m in re.finditer(rb"\r(?!\n)", data)], "a carriage return is not followed by a line feed")
    if data and not data.endswith(b"\n"):
        problems.append((line_of(data, len(data)), "tc2", "the last line has no CRLF after it"))
    report("r8", [m.start() for m in re.finditer(rb"\t", data)], "a tab character; %s" % TAB_ADVICE[kind])
    wide = [i for i in range(start, len(data)) if data[i] > 0x7F]
    if wide:
        report("ascii", wide, "byte 0x%02X is not ASCII" % data[wide[0]])
    controls = [i for i in range(len(data)) if (data[i] < 0x20 and data[i] not in b"\t\r\n") or data[i] == 0x7F]
    if controls:
        report("ascii", controls, "control byte 0x%02X" % data[controls[0]])
    return problems


def check_width(lines, kind, inner=range(0)):
    """e2: 150 columns unless splitting is impractical, and 180 whatever. A C++ or Python line may take
    the extra thirty by saying so with r17's own WIDTH-EXEMPT mark, and a C++ line continued with a
    backslash takes them without one, because clang-format aligns every escaped newline at its 180-column
    limit (LLVM's AlignEscapedNewlines: Right) and a mark cannot follow the backslash. Project XML is
    IDE-owned and held to the hard cap alone. The prolog's inner lines are r17's to measure."""
    problems = []
    mark = WIDTH_MARK.get(kind)
    for index, line in enumerate(lines):
        if index in inner:
            continue
        width = len(line) - (3 if index == 0 and kind == MSBUILD and line.startswith("\xef\xbb\xbf") else 0)
        if width > HARD_WIDTH:
            problems.append((index + 1, "e2", "%d columns is past the hard cap of %d" % (width, HARD_WIDTH)))
        elif width > SOFT_WIDTH and mark is not None and not line.endswith(mark) and not (kind == CPP and line.endswith("\\")):
            problems.append((index + 1, "e2", "%d columns; wrap at %d, or end the line with '%s' if it cannot be split"
                             % (width, SOFT_WIDTH, mark.strip())))
    return problems


