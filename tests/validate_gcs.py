def blank_literals(lines):
    """Returns (code, directives): each line's code with comments removed, string and character literals
    reduced to empty quotes and preprocessor lines emptied, carrying block comments and raw strings
    across lines; and, per line, the name of the preprocessor directive it begins ('' for a directive's
    continuation line, None for a line that is not one). What is left is enough to see braces and
    parentheses, which is all the indent check needs."""
    code = []
    directives = []
    in_comment = False
    raw_end = None
    continued = False
    for line in lines:
        directive = None
        if not in_comment and raw_end is None:
            if continued:
                directive = ""
            else:
                match = re.match(r"\s*#\s*(\w*)", line)
                if match:
                    directive = match.group(1)
        out = []
        i = 0
        while i < len(line):
            if in_comment:
                end = line.find("*/", i)
                if end < 0:
                    break
                in_comment = False
                out.append(" ")
                i = end + 2
                continue
            if raw_end is not None:
                end = line.find(raw_end, i)
                if end < 0:
                    break
                i = end + len(raw_end)
                raw_end = None
                out.append('""')
                continue
            c = line[i]
            if line.startswith("//", i):
                break
            if line.startswith("/*", i):
                in_comment = True
                i += 2
                continue
            if c == '"':
                if re.search(r"(?:^|[^A-Za-z0-9_])(?:u8|u|U|L)?R$", line[:i]):
                    opening = line.find("(", i)
                    if opening >= 0:
                        raw_end = ")" + line[i + 1:opening] + '"'
                        i = opening + 1
                        continue
                i += 1
                while i < len(line) and line[i] != '"':
                    i += 2 if line[i] == "\\" else 1
                out.append('""')
                i += 1
                continue
            if c == "'":
                # A digit separator, 1'000 or 0xFF'FF, sits inside a number; L'0' and u8'a' are prefixed
                # character literals, whose token starts with a letter rather than a digit.
                token = re.search(r"[A-Za-z0-9_.']*$", line[:i]).group(0)
                if token[:1].isdigit() and i + 1 < len(line) and line[i + 1].isalnum():
                    i += 1
                    continue
                i += 1
                while i < len(line) and line[i] != "'":
                    i += 2 if line[i] == "\\" else 1
                out.append("''")
                i += 1
                continue
            out.append(c)
            i += 1
        if directive is not None:
            continued = line.endswith("\\")
            code.append("")
        else:
            code.append("".join(out))
        directives.append(directive)
    return code, directives


def brace_kind(before, previous_end, inside_initializer):
    """'init' for a braced initializer, whose rows clang-format aligns rather than indents; 'block'
    for anything whose body is indented one step: a function, a control statement, a struct, an enum, a
    lambda or a bare scope. clang-format writes a space before a block's brace and none before a braced
    list, so `S s{` and `TABLE[]{` are lists where `struct S {` and `) {` are blocks."""
    if inside_initializer:
        return "init"
    text = before.rstrip()
    if not text:
        return "init" if previous_end in ("=", "(", ",", "[", "?") else "block"
    if text[-1] in "=(,[{?" or re.search(r"(^|[^A-Za-z0-9_])return$", text):
        return "init"
    if before[-1:] and (before[-1].isalnum() or before[-1] in "_>]"):
        return "init"
    return "block"


LABEL = re.compile(r"[A-Za-z_]\w*\s*:(?!:)")
CASE_LABEL = re.compile(r"(case\b.*|default\s*):")
ACCESS = re.compile(r"(public|private|protected)\s*:")
CONTROL_HEAD = re.compile(r"(\}\s*)?(else\s+)?(if|for|while)\s*\(")
BARE_HEAD = re.compile(r"(\}\s*)?(else|do)")
CARRIED_HEAD = re.compile(r"template\s*<.*>|\[\[.*\]\]")


def check_indent(lines):
    """r8, made mechanical over the brace structure rather than over every line, because a continuation
    line is aligned rather than indented and belongs to no step. A statement that starts inside a block
    starts exactly three spaces past the line that opened it, a brace-less body of if, for, while, else
    or do three past its head, a closing brace lines up with its opener, and a statement at file scope
    starts in column one. The exceptions are the ones .clang-format itself makes: a case label and a goto
    label sit at the opener's column (IndentCaseLabels false and IndentGotoLabels true, LLVM's), an access
    specifier one column in (AccessModifierOffset -2 on a three-space step), and an extern "C" block's
    body is not indented at all. Each branch of an #if is read from the state the #if found, and the
    first branch's state is kept at #endif, so alternative opening lines do not unbalance the braces."""
    problems = []
    code, directives = blank_literals(lines)
    state = {"stack": [], "depth": 0, "previous": "", "statement": 0, "text": "", "body": None, "carry": None}
    conditionals = []
    for index, raw in enumerate(lines):
        directive = directives[index]
        if directive is not None:
            if directive in ("if", "ifdef", "ifndef"):
                conditionals.append({"start": copy.deepcopy(state), "first": None})
            elif directive in ("elif", "else", "elifdef", "elifndef") and conditionals:
                frame = conditionals[-1]
                if frame["first"] is None:
                    frame["first"] = copy.deepcopy(state)
                state = copy.deepcopy(frame["start"])
            elif directive == "endif" and conditionals:
                frame = conditionals.pop()
                if frame["first"] is not None:
                    state = frame["first"]
            continue
        line_code = code[index]
        text = line_code.strip()
        if not text:
            continue
        indent = len(raw) - len(raw.lstrip(" "))
        stack = state["stack"]
        top = stack[-1] if stack else None
        body = state["body"]
        state["body"] = None
        carry = state["carry"]
        state["carry"] = None
        in_enum = top is not None and top["enum"]
        starts = body is not None or carry is not None or (state["depth"] == 0 and (
            state["previous"] in ("", ";", "{", "}", ":") or (state["previous"] == "," and in_enum)))
        if starts and not text.startswith("}") and not (text.startswith("{") and body is not None):
            if body is not None:
                expected = body + CPP_STEP
            elif carry is not None:
                expected = carry
            elif top is None:
                expected = 0
            elif top["kind"] == "init":
                expected = None
            elif top["extern"]:
                expected = top["indent"]
            elif CASE_LABEL.match(text) and top["switch"]:
                expected = top["indent"]
            elif ACCESS.match(text):
                expected = top["indent"] + CPP_STEP - 2
            elif LABEL.match(text) and not CASE_LABEL.match(text):
                expected = top["indent"]
            else:
                expected = top["indent"] + CPP_STEP
            if expected is not None and indent != expected:
                problems.append((index + 1, "r8", "this statement starts at column %d; its block puts it at column %d"
                                 % (indent + 1, expected + 1)))
            state["statement"] = indent
            state["text"] = text
            if CARRIED_HEAD.fullmatch(text) and expected is not None:
                state["carry"] = expected
        first = len(line_code) - len(line_code.lstrip(" "))
        for position, c in enumerate(line_code):
            if c in "([":
                state["depth"] += 1
            elif c in ")]":
                state["depth"] = max(0, state["depth"] - 1)
            elif c == "{":
                before = line_code[:position]
                kind = brace_kind(before, state["previous"], bool(stack) and stack[-1]["kind"] == "init")
                owner = state["text"]
                entry = {"kind": kind, "indent": state["statement"], "saved": None,
                         "switch": kind == "block" and bool(re.match(r"(\}\s*)?switch\s*\(", owner)),
                         "extern": kind == "block" and bool(re.fullmatch(r'extern\s*""', before.strip())),
                         "enum": kind == "block" and bool(re.match(r"(typedef\s+)?enum\b", owner)) and "(" not in before}
                if kind == "block" and state["depth"] > 0:
                    # A lambda's body: indented from the line its brace opens on, and outside the parentheses
                    # the call around it left open.
                    entry["indent"] = indent
                    entry["saved"] = state["depth"]
                    state["depth"] = 0
                stack.append(entry)
            elif c == "}":
                if not stack:
                    problems.append((index + 1, "r8", "a closing brace with no opening brace before it"))
                    continue
                entry = stack.pop()
                if entry["saved"] is not None:
                    state["depth"] = entry["saved"]
                if position == first:
                    if entry["kind"] == "block" and indent != entry["indent"]:
                        problems.append((index + 1, "r8", "this closing brace is at column %d; the line that opened it starts "
                                         "at column %d" % (indent + 1, entry["indent"] + 1)))
                    state["statement"] = entry["indent"]
                    state["text"] = text
        state["previous"] = text[-1]
        if state["depth"] == 0 and text[-1] == ")" and CONTROL_HEAD.match(state["text"]):
            state["body"] = state["statement"]
        elif BARE_HEAD.fullmatch(text):
            state["body"] = state["statement"]
    return problems


