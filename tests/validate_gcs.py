# r8: three-space indentation in C and C++


def blank_literals(lines):
    """Returns each line's code with comments removed, string and character literals reduced to empty
    quotes and preprocessor lines emptied, carrying block comments and raw strings across lines. What is
    left is enough to see braces and parentheses, which is all the indent check needs."""
    code = []
    in_comment = False
    raw_end = None
    continued = False
    for line in lines:
        if not in_comment and raw_end is None and (continued or line.lstrip(" ").startswith("#")):
            continued = line.endswith("\\")
            code.append("")
            continue
        out = []
        i = 0
        while i < len(line):
            if in_comment:
                end = line.find("*/", i)
                if end < 0:
                    i = len(line)
                    break
                in_comment = False
                out.append(" ")
                i = end + 2
                continue
            if raw_end is not None:
                end = line.find(raw_end, i)
                if end < 0:
                    i = len(line)
                    break
                i = end + len(raw_end)
                raw_end = None
                out.append('""')
                continue
            c = line[i]
            if c == "/" and line.startswith("//", i):
                break
            if c == "/" and line.startswith("/*", i):
                in_comment = True
                i += 2
                continue
            if c == '"':
                prefix = re.search(r"(?:^|[^A-Za-z0-9_])(?:u8|u|U|L)?R$", line[:i])
                if prefix:
                    opening = line.find("(", i)
                    if opening >= 0:
                        raw_end = ")" + line[i + 1:opening] + '"'
                        i = opening + 1
                        continue
                i += 1
                while i < len(line) and line[i] != '"':
                    i += 2 if line[i] == "\\" else 1
                out.append('""')
                i += 1
                continue
            if c == "'":
                # A digit separator, 1'000 or 0xFF'FF, sits inside a number; L'0' and u8'a' are prefixed
                # character literals, whose token starts with a letter rather than a digit.
                token = re.search(r"[A-Za-z0-9_.']*$", line[:i]).group(0)
                if token[:1].isdigit() and i + 1 < len(line) and line[i + 1].isalnum():
                    i += 1
                    continue
                i += 1
                while i < len(line) and line[i] != "'":
                    i += 2 if line[i] == "\\" else 1
                out.append("''")
                i += 1
                continue
            out.append(c)
            i += 1
        code.append("".join(out))
    return code


def brace_kind(before, previous_end, inside_initializer):
    """'init' for a braced initializer, whose rows clang-format aligns rather than indents; 'block'
    for anything whose body is indented one step: a function, a control statement, a struct or an enum."""
    if inside_initializer:
        return "init"
    text = before.rstrip()
    last = text[-1:] if text else previous_end
    if last in ("=", "(", ",", "[", "{", "?") or re.search(r"(^|[^A-Za-z0-9_])return$", text):
        return "init"
    return "block"


def check_indent(lines):
    """r8, made mechanical over the brace structure rather than over every line, because a continuation
    line is aligned rather than indented and belongs to no step. Every statement that starts inside a
    block starts exactly three spaces past the statement that opened it, a closing brace lines up with
    that statement, and a statement at file scope starts in column one. The exceptions are the ones
    .clang-format itself makes: a case label sits at its switch (IndentCaseLabels is LLVM's false), an
    access specifier one column in (AccessModifierOffset -2 on a three-space step), and an extern "C"
    body not indented at all."""
    problems = []
    code = blank_literals(lines)
    stack = []
    depth = 0
    previous_end = ""
    statement = 0
    statement_text = ""
    for index, raw in enumerate(lines):
        text = code[index].strip()
        if not text:
            continue
        indent = len(raw) - len(raw.lstrip(" "))
        top = stack[-1] if stack else None
        in_enum = top is not None and top["enum"]
        starts = depth == 0 and (previous_end in ("", ";", "{", "}", ":") or (previous_end == "," and in_enum))
        if starts and not text.startswith("}"):
            statement = indent
            statement_text = text
            expected = None
            if top is None:
                expected = 0
            elif top["kind"] == "init":
                expected = None
            elif top["extern"]:
                expected = top["indent"]
            elif top["switch"] and re.match(r"(case\b.*|default\s*):", text):
                expected = top["indent"]
            elif re.match(r"(public|private|protected)\s*:", text):
                expected = top["indent"] + CPP_STEP - 2
            else:
                expected = top["indent"] + CPP_STEP
            if expected is not None and indent != expected:
                problems.append((index + 1, "r8", "this statement starts at column %d; its block puts it at column %d"
                                 % (indent + 1, expected + 1)))
        line_code = code[index]
        first = len(line_code) - len(line_code.lstrip(" "))
        for position, c in enumerate(line_code):
            if c in "([":
                depth += 1
            elif c in ")]":
                depth = max(0, depth - 1)
            elif c == "{":
                kind = brace_kind(line_code[:position], previous_end, bool(stack) and stack[-1]["kind"] == "init")
                owner = statement_text
                stack.append({"kind": kind, "indent": statement,
                              "switch": kind == "block" and bool(re.match(r"switch\s*\(", owner)),
                              "extern": kind == "block" and owner.startswith('extern ""'),
                              "enum": kind == "block" and bool(re.search(r"(^|\s)enum(\s|$)", owner))})
            elif c == "}":
                if not stack:
                    problems.append((index + 1, "r8", "a closing brace with no opening brace before it"))
                    continue
                entry = stack.pop()
                if position == first:
                    if entry["kind"] == "block" and indent != entry["indent"]:
                        problems.append((index + 1, "r8", "this closing brace is at column %d; the statement it closes starts "
                                         "at column %d" % (indent + 1, entry["indent"] + 1)))
                    statement = entry["indent"]
                    statement_text = text
        previous_end = text[-1]
    return problems


# ---------------------------------------------------------------------------------------------------
# Python: the tagged deviations, and the four-space step they allow


def check_python(data):
    """en3: r17's prolog cannot be written in Python, so the file says so on its first line instead of
    deviating silently. r8's exemption is .editorconfig's four spaces, so every indent steps by four."""
    problems = []
    text = data.decode("latin-1").replace("\r\n", "\n")
    if not text.startswith(PYTHON_TAG):
        problems.append((1, "en3", "a Python file opens with '%s' and its reason, standing in for the r17 prolog"
                         % PYTHON_TAG.strip()))
    widths = [0]
    try:
        for token in tokenize.generate_tokens(io.StringIO(text).readline):
            if token.type == tokenize.INDENT:
                width = len(token.string)
                if width - widths[-1] != PYTHON_STEP:
                    problems.append((token.start[0], "r8", "this block is indented %d past its parent; Python steps by %d "
                                     "(.editorconfig RULE-DEV:r8)" % (width - widths[-1], PYTHON_STEP)))
                widths.append(width)
            elif token.type == tokenize.DEDENT and len(widths) > 1:
                widths.pop()
    except (tokenize.TokenError, IndentationError, SyntaxError) as error:
        problems.append((0, "r8", "cannot tokenize this file: %s" % error))
    return problems


# ---------------------------------------------------------------------------------------------------
# One file


def check_file(rel, kind, data):
    """Every rule the file's class carries, as (line, rule, message) tuples sorted by line."""
    problems = check_bytes(data, kind)
    lines = split_lines(data)
    if kind == CPP:
        prolog, close = check_prolog(lines, rel.split("/")[-1])
        problems.extend(prolog)
        problems.extend(check_width(lines, kind, close))
        problems.extend(check_indent(lines))
    elif kind == PYTHON:
        problems.extend(check_width(lines, kind))
        problems.extend(check_python(data))
    else:
        problems.extend(check_width(lines, kind))
    return sorted(problems, key=lambda p: (p[0], p[1]))


