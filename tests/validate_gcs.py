# clang-format, pinned


def format_check(files, exe):
    """Runs clang-format in dry-run over the C++ files judged. The verdict is pinned to one release,
    because two releases can format one file two ways and CI must not change its mind when a runner
    image does; 18.1.3 is what every session since M1 verified the tree against."""
    found = shutil.which(exe) or (exe if os.path.isfile(exe) else None)
    if found is None:
        return [("clang-format", 0, FORMAT_RULE, "clang-format was not found; pip install clang-format==%s, or pass "
                 "--clang-format <path>" % CLANG_FORMAT_VERSION)]
    version = subprocess.run([found, "--version"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, cwd=REPO)
    match = re.search(r"clang-format version (\d+\.\d+\.\d+)", version.stdout.decode("utf-8", "replace"))
    if not match or match.group(1) != CLANG_FORMAT_VERSION:
        return [("clang-format", 0, FORMAT_RULE, "the formatter verdict is pinned to clang-format %s, and %s is %s"
                 % (CLANG_FORMAT_VERSION, found, match.group(1) if match else "an unknown version"))]
    cpp = [rel for rel, kind in files if kind == CPP]
    problems = []
    for start in range(0, len(cpp), 40):
        batch = cpp[start:start + 40]
        done = subprocess.run([found, "--dry-run", "--Werror", "--style=file"] + batch, stdout=subprocess.PIPE,
                              stderr=subprocess.STDOUT, cwd=REPO)
        if done.returncode != 0:
            output = done.stdout.decode("utf-8", "replace")
            reported = set()
            for hit in re.finditer(r"^(.+?):(\d+):\d+: (?:error|warning): (.*)$", output, re.M):
                where = relative(os.path.join(REPO, hit.group(1))) or hit.group(1)
                if (where, hit.group(2)) not in reported:
                    reported.add((where, hit.group(2)))
                    problems.append((where, int(hit.group(2)), FORMAT_RULE, "clang-format would change this line"))
            if not reported:
                problems.append((" ".join(batch), 0, FORMAT_RULE, "clang-format failed: %s" % output.strip()[:300]))
    return problems


# ---------------------------------------------------------------------------------------------------
# Reporting and the command line


def annotate(rel, line, rule, message):
    """A GitHub Actions error annotation, so a failure lands on the line in the pull request's diff."""
    def escape(text, extra=""):
        text = text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
        for c in extra:
            text = text.replace(c, "%%%02X" % ord(c))
        return text
    where = "file=%s" % escape(rel, ":,")
    if line:
        where += ",line=%d" % line
    return "::error %s,title=%s::%s" % (where, escape("GCS " + rule, ":,"), escape(message))


def show(problems):
    on_github = os.environ.get("GITHUB_ACTIONS") == "true"
    for rel, line, rule, message in problems:
        print("%s:%s %s: %s" % (rel, "%d:" % line if line else "", rule, message))
        if on_github:
            print(annotate(rel, line, rule, message))


def main(argv):
    args = list(argv)
    want_format = "--format" in args
    exe = "clang-format"
    if "--self-test" in args:
        return self_test()
    if "--clang-format" in args:
        at = args.index("--clang-format")
        if at + 1 >= len(args):
            print("validate_gcs: --clang-format needs a path")
            return 2
        exe = args[at + 1]
        del args[at:at + 2]
    args = [a for a in args if a != "--format"]
    unknown = [a for a in args if a.startswith("--")]
    if unknown:
        print("validate_gcs: unknown option %s" % unknown[0])
        print(__doc__.split("\n\n")[1])
        return 2

    notes = []
    try:
        files, problems = select(args, notes)
    except UsageError as error:
        print("validate_gcs: %s" % error)
        return 2
    for note in notes:
        print(note)
    if not files and not problems:
        print("validate_gcs: nothing to check")
        return 2

    for rel, kind in files:
        with open(os.path.join(REPO, rel), "rb") as handle:
            data = handle.read()
        problems.extend((rel, line, rule, message) for line, rule, message in check_file(rel, kind, data))
    if want_format:
        problems.extend(format_check(files, exe))
    show(problems)
    touched = len({p[0] for p in problems})
    print("validate_gcs: %d file%s judged, %d problem%s in %d file%s" % (
        len(files), "" if len(files) == 1 else "s", len(problems), "" if len(problems) == 1 else "s",
        touched, "" if touched == 1 else "s"))
    return 1 if problems else 0


