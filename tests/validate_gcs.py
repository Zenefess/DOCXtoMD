def split_lines(data):
    """Splits decoded text into lines without their terminators. Latin-1 maps each byte to one
    character, so a column is a byte; a byte that is not ASCII is the ASCII rule's to report."""
    text = data.decode("latin-1")
    lines = text.split("\n")
    if lines and lines[-1] == "":
        lines.pop()
    return [line[:-1] if line.endswith("\r") else line for line in lines]


def line_of(data, offset):
    return data.count(b"\n", 0, offset) + 1


def check_bytes(data, kind):
    """tc2's CRLF, r8's no tabs, and ASCII. Each rule reports its first offence and how many there
    are, because a file saved with the wrong settings breaks one of them on every line."""
    problems = []
    body = data
    start = 0
    if kind == MSBUILD and data.startswith(UTF8_BOM):
        start = len(UTF8_BOM)

    def report(rule, offsets, what):
        if offsets:
            more = "" if len(offsets) == 1 else " (%d in all)" % len(offsets)
            problems.append((line_of(body, offsets[0]), rule, what + more))

    bare_lf = [m.start() for m in re.finditer(rb"(?<!\r)\n", body)]
    bare_cr = [m.start() for m in re.finditer(rb"\r(?!\n)", body)]
    report("tc2", bare_lf, "a line ends LF rather than CRLF")
    report("tc2", bare_cr, "a carriage return is not followed by a line feed")
    if body and not body.endswith(b"\n"):
        problems.append((line_of(body, len(body)), "tc2", "the last line has no CRLF after it"))
    tabs = [m.start() for m in re.finditer(rb"\t", body)]
    report("r8", tabs, "a tab character; indent with three spaces")
    wide = [i for i in range(start, len(body)) if body[i] > 0x7F]
    if wide:
        report("ascii", wide, "byte 0x%02X is not ASCII" % body[wide[0]])
    controls = [i for i in range(len(body)) if (body[i] < 0x20 and body[i] not in b"\t\r\n") or body[i] == 0x7F]
    if controls:
        report("ascii", controls, "control byte 0x%02X" % body[controls[0]])
    return problems


def check_width(lines, kind, skip_until=-1):
    """e2: 150 columns unless splitting is impractical, and 180 whatever. A C++ or Python line may take
    the extra thirty only by saying so with r17's own WIDTH-EXEMPT mark; project XML is IDE-owned and
    held to the hard cap alone."""
    problems = []
    mark = WIDTH_MARK.get(kind)
    for index, line in enumerate(lines):
        if index <= skip_until:
            continue
        width = len(line)
        if index == 0 and line.startswith("\xef\xbb\xbf"):
            width -= 3
        if width > HARD_WIDTH:
            problems.append((index + 1, "e2", "%d columns is past the hard cap of %d" % (width, HARD_WIDTH)))
        elif width > SOFT_WIDTH and mark is not None and not line.endswith(mark):
            problems.append((index + 1, "e2", "%d columns; wrap at %d, or end the line with '%s' if it cannot be split"
                             % (width, SOFT_WIDTH, mark.strip())))
    return problems


