# clang-format, pinned


def format_check(files, exe, root=REPO):
    """Runs clang-format in dry-run over the C++ files judged. The verdict is pinned to one release,
    because two releases can format one file two ways and CI must not change its mind when a runner
    image does; 18.1.3 is what every session since M1 verified the tree against."""
    if os.sep in exe or "/" in exe:
        found = os.path.abspath(exe) if os.path.isfile(exe) else None
    else:
        found = shutil.which(exe)
    if found is None:
        return [("clang-format", 0, FORMAT_RULE, "%s was not found; pip install clang-format==%s, or pass --clang-format <path>"
                 % (exe, CLANG_FORMAT_VERSION))]
    try:
        version = subprocess.run([found, "--version"], stdout=subprocess.PIPE, stderr=subprocess.STDOUT, cwd=root)
    except OSError as error:
        return [("clang-format", 0, FORMAT_RULE, "%s cannot be run: %s" % (found, error.strerror))]
    match = re.search(r"clang-format version (\d+\.\d+\.\d+)", version.stdout.decode("utf-8", "replace"))
    if not match or match.group(1) != CLANG_FORMAT_VERSION:
        return [("clang-format", 0, FORMAT_RULE, "the formatter verdict is pinned to clang-format %s, and %s is %s"
                 % (CLANG_FORMAT_VERSION, found, match.group(1) if match else "an unknown version"))]
    cpp = [rel for rel, kind in files if kind == CPP]
    problems = []
    for start in range(0, len(cpp), 40):
        batch = cpp[start:start + 40]
        done = subprocess.run([found, "--dry-run", "--Werror", "--style=file"] + batch, stdout=subprocess.PIPE,
                              stderr=subprocess.STDOUT, cwd=root)
        if done.returncode != 0:
            output = done.stdout.decode("utf-8", "replace")
            reported = set()
            for hit in re.finditer(r"^(.+?):(\d+):\d+: (?:error|warning): (.*)$", output, re.M):
                where = os.path.relpath(os.path.join(root, hit.group(1)), root).replace(os.sep, "/")
                if (where, hit.group(2)) not in reported:
                    reported.add((where, hit.group(2)))
                    problems.append((where, int(hit.group(2)), FORMAT_RULE, "clang-format would change this line"))
            if not reported:
                problems.append((" ".join(batch), 0, FORMAT_RULE, "clang-format failed: %s" % output.strip()[:300]))
    return problems


