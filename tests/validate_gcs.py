# RULE-DEV:r17 GCS r17's file prolog is a C block comment, which Python cannot carry. The module
# docstring below holds the same information in the form the language allows.
"""The mechanical half of GCS v1.1.4, run over src/ and tests/ -- decision D11's validator.

    python tests/validate_gcs.py                     src/ and tests/, which is what CI runs
    python tests/validate_gcs.py src/Ir.h tests/unit only what is named, inside the same scope
    python tests/validate_gcs.py --format            and clang-format 18.1.3 must be a no-op
    python tests/validate_gcs.py --self-test         every rule shown firing on a known-bad input

What a machine can check without a compiler, it checks: the r17 prolog (the standard's own regexes and
its twelve fields in order), r8's three-space indent and its ban on tabs, e2's 150 and 180 columns,
tc2's CRLF, and ASCII -- the sources carry no BOM and the project does not pass /utf-8, so a non-ASCII
byte would be read in whatever code page the compiler runs under. Everything else stays with review:
naming, the typedef lattice, whether a comment is true.

include/ is exempt, and the exemption lives here rather than in the CI invocation so that a hand run
cannot reach a different verdict (D11). The six owner-authored headers carry a nonconforming ISA token
and two pre-r17 banners that CLAUDE.md says to report, not fix, so a path under include/ is never judged
however it is named. tests/fixtures/ is input data (.editorconfig's RULE-DEV:tc2), and tests/build/,
tests/x64/ and __pycache__/ are generated, so none of those is judged either. Any other file under
src/ or tests/ whose type this script has no rules for is a failure rather than a silent pass: a new
kind of file is a decision, and this is where it is made.

Exit status: 0 clean, 1 at least one problem, 2 a usage error or nothing to check.
"""

import datetime
import io
import os
import re
import shutil
import subprocess
import sys
import tokenize

ROOT = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(ROOT)

# The two directories D11 names. A run with no arguments judges exactly these.
SCOPE = ("src", "tests")

# Never judged, whatever the command line says. The reason is printed when a named path lands here.
EXEMPT = "include"
EXEMPT_REASON = "exempt under D11 -- the owner-authored headers are reported, not fixed"
SKIPPED_DIRS = {
    "tests/fixtures": "fixture parts are input data, byte for byte (.editorconfig RULE-DEV:tc2)",
    "tests/build": "generated by make_fixtures.py",
    "tests/x64": "build output of the unit-test project",
}
SKIPPED_NAMES = {"__pycache__": "generated by CPython"}
SKIPPED_SUFFIXES = {".vcxproj.user": "Visual Studio's per-user settings"}

# What each kind of file is held to. C and C++ carry every rule. Python carries a tagged r17 deviation
# and a tagged four-space indent (.editorconfig's RULE-DEV:r8), so its prolog check is the tag itself.
# MSBuild XML is written and rewritten by Visual Studio, two-space indented, with <Import> elements of
# 179 columns it puts back on every save: r8 does not reach it and e2's "unless splitting is
# impractical" is exactly its case, so only the hard cap binds -- RULE-DEV:r8,e2 for IDE-owned XML.
CPP = "C++"
PYTHON = "Python"
MSBUILD = "MSBuild"
CLASSES = {
    ".c": CPP, ".cpp": CPP, ".h": CPP, ".hpp": CPP, ".inl": CPP,
    ".py": PYTHON,
    ".vcxproj": MSBUILD, ".filters": MSBUILD, ".props": MSBUILD,
}

SOFT_WIDTH = 150
HARD_WIDTH = 180
WIDTH_MARK = {CPP: " // WIDTH-EXEMPT", PYTHON: " # WIDTH-EXEMPT"}
PYTHON_TAG = "# RULE-DEV:r17 "
PYTHON_STEP = 4
CPP_STEP = 3
CLANG_FORMAT_VERSION = "18.1.3"
UTF8_BOM = b"\xef\xbb\xbf"

# r17's "Validation (minimal)", verbatim from GDC_GCS_v1_1_4.md.
PROLOG_OPEN = re.compile(r"^\s*/\*\s*$")
PROLOG_CLOSE = re.compile(r"^\s*\*/\s*$")
PROLOG_INNER = re.compile(r"^ \*(| .{0,147}| .{0,161} // WIDTH-EXEMPT)$")
PROLOG_DATE = re.compile(r"^ \* (Created|Last Modified): \d{4}-\d{2}-\d{2}$")
PROLOG_VERSION = re.compile(r"^ \* Version: v\d+\.\d+(\.\d+)?$")
PROLOG_LICENSE = re.compile(r"^ \* License: [A-Za-z0-9.+-]+  Copyright: .+$")
ISA_TOKENS = ("Scalar", "SSE4.2", "AVX2", "AVX-512")
THREAD_SAFETY = ("N/A", "Reentrant", "MT-safe")

# r17's required fields, lettered A to L, in the order the standard lists them. Only these three may
# run onto a continuation line: To Do by r17's own words, and the two lists beside it.
FIELDS = ("File", "Version", "Owner", "Created", "Last Modified", "Description", "To Do", "Dependencies",
          "ISA", "Thread-safety", "Reviewers", "License")
MULTILINE = ("To Do", "Dependencies", "Reviewers")
PROLOG_SEARCH = 200

# Every rule a problem can be reported under, so the self-test can prove each one still fires.
RULES = ("r17", "r8", "e2", "tc2", "ascii", "en3", "scope")

# The formatter's findings are reported under tc1, the rule .clang-format implements. They need the pinned
# binary, so the self-test cannot fire them and RULES does not list them.
FORMAT_RULE = "tc1"


