def self_test():
    """Every check_file case names the problems it must produce, so deleting any report fails a case;
    the path and tree cases do the same for choosing what to judge."""
    failures = 0
    total = 0
    fired = set()
    for name, rel, data, wanted in file_cases():
        total += 1
        got = check_file(rel, verdict_for(rel)[1], data)
        fired |= {rule for _, rule, _ in got}
        if matches(got, wanted):
            print("ok    %s" % name)
        else:
            failures += 1
            print("FAIL  %s: wanted %s" % (name, wanted or "nothing"))
            for line, rule, message in got:
                print("        %d: %s: %s" % (line, rule, message))
    for rel, wanted in path_cases():
        total += 1
        got = verdict_for(rel)[0]
        if got == wanted:
            print("ok    %s is %s" % (rel, wanted))
        else:
            failures += 1
            print("FAIL  %s: wanted %s, got %s" % (rel, wanted, got))
    for name, got, wanted in [
            ("a quoted byte is escaped", ascii_only("caf\xe9"), "caf\\xe9"),
            ("an annotation escapes its properties and its message", annotate("a,b.cpp", 3, "r8", "50% done\n"),
             "::error file=a%2Cb.cpp,line=3,title=GCS r8::50%25 done%0A")]:
        total += 1
        if got == wanted:
            print("ok    %s" % name)
        else:
            failures += 1
            print("FAIL  %s: wanted %r, got %r" % (name, wanted, got))
    for argv, wanted in parse_cases():
        total += 1
        try:
            got = parse(argv)
        except UsageError:
            got = None
        if got == wanted:
            print("ok    %s %s" % ("parses" if wanted else "refuses", " ".join(argv) or "no arguments"))
        else:
            failures += 1
            print("FAIL  %s: wanted %s, got %s" % (" ".join(argv) or "no arguments", wanted, got))
    scratch = tempfile.mkdtemp(prefix="validate_gcs_")
    try:
        for name, ok, got in tree_cases(scratch):
            total += 1
            if ok:
                print("ok    %s" % name)
                if isinstance(got, tuple) and got[1]:
                    fired.add("scope")
            else:
                failures += 1
                print("FAIL  %s: got %s" % (name, got))
    finally:
        shutil.rmtree(scratch, ignore_errors=True)
    total += 2
    silent = [rule for rule in RULES if rule not in fired]
    if silent:
        failures += 1
        print("FAIL  no case shows these rules firing: %s" % ", ".join(silent))
    if __doc__ is not None and USAGE not in __doc__:
        failures += 1
        print("FAIL  USAGE and the module docstring's usage lines have drifted apart")
    print()
    if failures:
        print("%d of %d self-test checks failed" % (failures, total))
        return 1
    print("all %d self-test checks passed" % total)
    return 0


